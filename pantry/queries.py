def add_food(conn: Connection, food: Food) -> Food:
    """EXAMPLE — insert a food, store the id generated by PostgreSQL on the object."""
    with conn.cursor(cursor_factory=RealDictCursor) as cur:
        cur.execute(
            """
            INSERT INTO foods (name, category, stock, unit_price)
            VALUES (%s, %s, %s, %s)
            RETURNING id
            """,
            (food.name, food.category, food.stock, food.unit_price),
        )
        food.id = cur.fetchone()["id"]
    return food


