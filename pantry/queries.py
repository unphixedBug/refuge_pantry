def list_foods(conn: Connection) -> list[Row]:
    """EXAMPLE — every food, ordered by name (fetchall)."""
    with conn.cursor(cursor_factory=RealDictCursor) as cur:
        cur.execute(
            """
            SELECT id, name, category, stock, unit_price
            FROM foods
            ORDER BY name
            """
        )
        return cur.fetchall()


def get_food(conn: Connection, name: str) -> Food | None:
    """EXAMPLE — one food as a Food object, or None (fetchone + parameter)."""
    with conn.cursor(cursor_factory=RealDictCursor) as cur:
        cur.execute(
            "SELECT id, name, category, stock, unit_price FROM foods WHERE name = %s",
            (name,),  # a tuple, even with one value: note the comma
        )
        row = cur.fetchone()
    return Food.from_row(row) if row is not None else None


